#!/usr/bin/env node
// Generates a theme stylesheet from W3C DTCG design tokens.
//
//   node scripts/build-theme.mjs                          # src/tokens/tokens.json -> src/styles/themes/default.css
//   node scripts/build-theme.mjs src/tokens/acme.json acme  # -> src/styles/themes/acme.css
//   node scripts/build-theme.mjs --check                  # fail if the CSS is out of date
//
// The output defines CSS variables under [data-theme='<name>'] and [data-theme='<name>'].dark.
// Never edit the generated CSS by hand: edit the tokens and run this script.
// No dependencies; Node 18+.

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const check = args.includes('--check');
const [tokensArg = 'src/tokens/tokens.json', theme = 'default'] = args.filter((a) => a !== '--check');

if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(theme)) {
  console.error(`Theme name must be kebab-case: ${theme}`);
  process.exit(1);
}

const tokens = JSON.parse(readFileSync(resolve(root, tokensArg), 'utf8'));

function resolveRef(value, seen = new Set()) {
  const match = typeof value === 'string' && value.match(/^\{(.+)\}$/);
  if (!match) return value;
  const path = match[1];
  if (seen.has(path)) throw new Error(`Circular token reference: ${path}`);
  seen.add(path);
  const node = path.split('.').reduce((acc, key) => acc?.[key], tokens);
  if (!node || !('$value' in node)) throw new Error(`Unknown token reference: {${path}}`);
  return resolveRef(node.$value, seen);
}

function block(selector, colors, extra = []) {
  const lines = Object.entries(colors).map(([name, token]) => `  --${name}: ${resolveRef(token.$value)};`);
  return `${selector} {\n${[...lines, ...extra].join('\n')}\n}\n`;
}

const { light, dark, radius } = tokens.semantic;
const css =
  `/* Generated by scripts/build-theme.mjs from ${tokensArg}. Do not edit by hand. */\n` +
  block(`[data-theme='${theme}']`, light.color, [`  --radius: ${resolveRef(radius.$value)};`]) +
  block(`[data-theme='${theme}'].dark`, dark.color);

const out = resolve(root, `src/styles/themes/${theme}.css`);
if (check) {
  const current = existsSync(out) ? readFileSync(out, 'utf8') : '';
  if (current !== css) {
    console.error(`src/styles/themes/${theme}.css is out of date. Run: node scripts/build-theme.mjs ${tokensArg} ${theme}`);
    process.exit(1);
  }
  console.log(`src/styles/themes/${theme}.css is up to date`);
} else {
  writeFileSync(out, css);
  console.log(`wrote src/styles/themes/${theme}.css`);
}
